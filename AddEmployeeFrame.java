private void loadDepartments() {
    cmbDepartment.removeAllItems();
    for (Department d : dm.getAllDepartments()) {
        cmbDepartment.addItem(d);
    }
}

private void showSalaryFields() {
    CardLayout cl = (CardLayout) pnlSalary.getLayout();
    if (cmbType.getSelectedItem().equals("Full Time")) {
        cl.show(pnlSalary, "FULL");
    } else {
        cl.show(pnlSalary, "PART");
    }
}

private void clearFields() {
    txtID.setText("");
    txtFullName.setText("");
    txtAge.setText("");
    txtPosition.setText("");
    txtBasicSalary.setText("");
    txtBonus.setText("");
    txtHourlyRate.setText("");
    txtHoursWorked.setText("");
    cmbType.setSelectedIndex(0);
    if (cmbDepartment.getItemCount() > 0) cmbDepartment.setSelectedIndex(0);
}

private String requireText(JTextField f, String fieldName) {
    String t = f.getText().trim();
    if (t.isEmpty()) {
        f.requestFocus();
        throw new IllegalArgumentException(fieldName + " is required.");
    }
    return t;
}

private int readInt(JTextField f, String fieldName) {
    try {
        return EmployeeManager.parseInt(f.getText(), fieldName);
    } catch (IllegalArgumentException ex) {
        f.requestFocus();
        throw ex;
    }
}

private double readDouble(JTextField f, String fieldName) {
    try {
        return EmployeeManager.parseDouble(f.getText(), fieldName);
    } catch (IllegalArgumentException ex) {
        f.requestFocus();
        throw ex;
    }
}
