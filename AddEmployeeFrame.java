    private void btnAddActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnAddActionPerformed
        try {
    int id = readInt(txtID, "Employee ID");
    String name = requireText(txtFullName, "Full name");
    int age = readInt(txtAge, "Age");
    String position = requireText(txtPosition, "Position");

    Department dep = (Department) cmbDepartment.getSelectedItem();
    if (dep == null)
        throw new IllegalArgumentException("Please select a department.");

    String type = (String) cmbType.getSelectedItem();
    if (type.equals("Full Time")) {
        double basic = readDouble(txtBasicSalary, "Basic salary");
        double bonus = readDouble(txtBonus, "Bonus");
        em.addFullTimeEmployee(id, name, age, position, dep, basic, bonus);
    } else if (type.equals("Part Time")) {
        double rate = readDouble(txtHourlyRate, "Hourly rate");
        double hours = readDouble(txtHoursWorked, "Hours worked");
        em.addPartTimeEmployee(id, name, age, position, dep, rate, hours);
    } else {
        throw new IllegalArgumentException("Unsupported employee type.");
    }

    JOptionPane.showMessageDialog(this, "Employee added successfully!");
    clearFields();

} catch (IllegalArgumentException ex) {
    JOptionPane.showMessageDialog(this, ex.getMessage(), "Invalid input", JOptionPane.ERROR_MESSAGE);
} catch (IOException ex) {
    JOptionPane.showMessageDialog(this, "Could not save data: " + ex.getMessage(), "File error", JOptionPane.ERROR_MESSAGE);
}
    }//GEN-LAST:event_btnAddActionPerformed

