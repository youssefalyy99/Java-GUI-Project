    private void loadEmployees() {
    try {
        departments = fileHandler.loadDepartments();
        employees = fileHandler.loadEmployees(departments);
    } catch (IOException e) {
        JOptionPane.showMessageDialog(this, "Could not read files: " + e.getMessage());
        return;
    }

    DefaultTableModel model = new DefaultTableModel(
        new String[]{"ID", "Full Name", "Age", "Type", "Position",
                     "Department ID", "Basic Salary / Hourly Rate", "Bonus / Hours Worked"}, 0) {
        @Override public boolean isCellEditable(int r, int c) { return false; }
    };

    for (Employee e : employees) {
        String type = (e instanceof FullTimeEmployee) ? "Full Time" : "Part Time";

        // toCSVLine() is "id,name,age,type,position,depId,a,b" (same format FileHandler reads),
        // so the last two fields are the Basic Salary/Hourly Rate and Bonus/Hours Worked values.
        String[] p = e.toCSVLine().split(",");

        model.addRow(new Object[]{
            e.getID(),
            e.getFullName(),
            e.getAge(),
            type,
            e.getPosition(),
            e.getDep().getDepartmentID(),
            p[6].trim(),
            p[7].trim()
        });
    }
    jTable1.setModel(model);
}

    private void jButton1ActionPerformed(java.awt.event.ActionEvent evt) {
        loadEmployees();
    }

    private void jButton4ActionPerformed(java.awt.event.ActionEvent evt) {
        int row = jTable1.getSelectedRow();
        if (row == -1) {
            JOptionPane.showMessageDialog(this, "Select an employee first.");
            return;
        }
        int id = (int) jTable1.getValueAt(row, 0);

        int confirm = JOptionPane.showConfirmDialog(
            this, "Delete this employee?", "Confirm", JOptionPane.YES_NO_OPTION);
        if (confirm != JOptionPane.YES_OPTION) return;

        employees.removeIf(e -> e.getID() == id);
        try {
            fileHandler.saveEmployees(employees);
        } catch (IOException ex) {
            JOptionPane.showMessageDialog(this, "Could not save: " + ex.getMessage());
            return;
        }
        loadEmployees();
    }

