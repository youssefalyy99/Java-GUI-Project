    private void searchButtonActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_searchButtonActionPerformed
        try {
            String choice = (String) searchByBox.getSelectedItem();
            String text = searchField.getText();
            java.util.List<Employee> result;
            if (choice.equals("ID")) {
                result = manager.searchById(text);
            } else if (choice.equals("Name")) {
                result = manager.searchByName(text);
            } else {
                result = manager.searchByDepartmentName(text);
            }

            if (result.isEmpty()) {
                javax.swing.JOptionPane.showConfirmDialog(this, "No matching employee found.");
            }
            refreshTable(result);
        } catch (IllegalArgumentException ex) {
            javax.swing.JOptionPane.showMessageDialog(this, ex.getMessage(),
                    "Invalid Input", javax.swing.JOptionPane.ERROR_MESSAGE);
        }


    }//GEN-LAST:event_searchButtonActionPerformed

